const l = (i: string, ml: number, t?: string, opt?: boolean): RecipeLine => ({ i, ml, t, opt })
const L = (color: string, weight = 1): Layer => [color, weight]

interface Extras {
  ice?: boolean | 'crushed' | 'big'
  foam?: boolean
  bubbles?: boolean
  frozen?: boolean
  straw?: boolean
  g?: Garnish[]
}
const ill = (glass: Glass, layers: Layer[], e: Extras = {}): IllustrationSpec => ({
  glass,
  layers,
  ice: e.ice,
  foam: e.foam,
  bubbles: e.bubbles,
  frozen: e.frozen,
  straw: e.straw,
  garnish: e.g,
})

